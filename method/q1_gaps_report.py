# Writes studies/concern-map/gaps-to-close.md from each platform's gaps.tsv: which gaps are open, who could close
# them, and how. Under PLAN.md (agreed 12 October 2026) gaps are closed only inside a subject that needs them, so
# this page is a reference, not a list of tasks.
# Usage: python3 -I q1_gaps_report.py STUDY_DIR
import csv, collections, os, sys

study = sys.argv[1]
NAMES = {"shopify": "Shopify", "salla": "Salla", "woocommerce": "WooCommerce", "zid": "Zid", "bigcommerce": "BigCommerce"}
DECLARATION_ONLY = {"zid", "bigcommerce"}   # read with no accounts, by the founder's choice (12 October 2026)
PLACEMENT = {"where": "where it lives", "decides": "who decides", "responsible": "who is legally responsible",
             "boundary": "how it meets the rest", "reason": "stated reason"}
KIND_ORDER = ["observation needed", "page not read", "stated only in general terms", "searched, not found"]

def rd(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))

def cell(text, n=220):
    t = " ".join(text.split()).replace("|", "\\|")
    return t if len(t) <= n else t[:n] + " [cut]"

held_log = os.path.join(study, "held-check.tsv")
rerouted = collections.Counter(r["platform"] for r in rd(held_log)) if os.path.exists(held_log) else {}
out = ["# Gaps (Q1): a reference", "",
       "Each platform's re-pass records a gap wherever the platform's own sources, as held, state nothing for a concern "
       "and placement. Under `PLAN.md`, a gap is closed only inside a subject that needs it. **Nothing on this page is "
       "asked of the founder.** When a subject needs a gap that only the founder can close, the gate for that subject "
       "says so, with the reason.", "",
       "On 12 October 2026, Stage 0 checked every gap against what observed-sa, observed-sh and this repository's "
       "capture runs hold. It re-routed the gaps whose page or corpus is held, without closing any. "
       "`held-check.tsv` lists each change and its rule. Generated by `method/q1_gaps_report.py`.", "",
       "Gap kinds:", "",
       "- **observation needed**: a journey, a store on a plan, a page saved from a browser, or a question to the platform would show it.",
       "- **page not read**: a named page, structure or corpus would likely state it, and it has not been read yet.",
       "- **stated only in general terms**: the platform's terms speak only of its services in general. Applying such a clause to one concern would be inference.",
       "- **searched, not found**: the likely pages and structures were read, as the row lists, and none states it.", ""]
for plat in ("shopify", "salla", "woocommerce", "zid", "bigcommerce"):
    gp = os.path.join(study, "platforms", plat, "gaps.tsv")
    if not os.path.exists(gp):
        continue
    gaps = rd(gp)
    con = {r["concern_id"]: r for r in rd(os.path.join(study, "platforms", plat, "concerns.tsv"))}
    by_kind = collections.Counter(r["gap_kind"] for r in gaps)
    by_who = collections.Counter(r["who_can"] for r in gaps)
    out += [f"## {NAMES[plat]}", "",
            f"{len(gaps)} gaps: " + ", ".join(f"{by_kind[k]} {k}" for k in KIND_ORDER if by_kind[k]) + ". "
            f"Who could close them: {by_who['agent']} an agent, {by_who['either']} either, {by_who['founder']} the founder."
            + (f" Stage 0 re-routed {rerouted[plat]}." if rerouted.get(plat) else ""), ""]
    agent = collections.Counter(r["means"] for r in gaps if r["who_can"] == "agent")
    if agent:
        out += ["**An agent could close these when a subject needs them:** " +
                "; ".join(f"{n} {m}" for m, n in agent.most_common()) + ".", ""]
    founder = [r for r in gaps if r["who_can"] in ("founder", "either")]
    if plat in DECLARATION_ONLY:
        obs = [r for r in founder if r["gap_kind"] == "observation needed"]
        founder = [r for r in founder if r["gap_kind"] != "observation needed"]
        if obs:
            out += [f"**Not asked: {len(obs)} need an account or a journey.** {NAMES[plat]} is read at declaration "
                    "level only, by the founder's choice of 12 October 2026.", ""]
    if not founder:
        continue
    groups = collections.OrderedDict()
    for r in sorted(founder, key=lambda r: (r["means"], r["concern_id"])):
        groups.setdefault((r["who_can"], r["means"]), []).append(r)
    out += ["**Would need the founder, if a subject needs them:**", ""]
    for (who, means), rows in groups.items():
        out += [f"### {means[0].upper() + means[1:]} ({who}, {len(rows)})", "",
                "| Concern | Placement | What would show it | Route |", "| --- | --- | --- | --- |"]
        for r in rows:
            name = con.get(r["concern_id"], {}).get("concern", "")
            out.append(f"| {r['concern_id']} {cell(name, 80)} | {PLACEMENT.get(r['placement'], r['placement'])} | "
                       f"{cell(r['what_would_show_it'])} | {cell(r['route'])} |")
        out.append("")
open(os.path.join(study, "gaps-to-close.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("written", os.path.join(study, "gaps-to-close.md"))
