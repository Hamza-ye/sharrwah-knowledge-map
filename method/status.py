"""Generates STATE.md from work.tsv and risks.tsv (PLAN.md, section 2.6). Nothing in STATE.md is written by hand.

    python3 -I method/status.py
"""
import csv, os, subprocess, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STAGES = {"0": "Reset and inception", "1": "Reference model and the first market's short list",
          "2": "Requirements and architecture", "3": "Walking skeleton", "4": "Core commerce increments",
          "5": "Extensibility and the Yemen market setup", "6": "Production readiness and pilot",
          "7": "Launch and operate", "8": "Second market"}


def rows(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def main():
    work, risks = rows("work.tsv"), rows("risks.tsv")
    open_ = [w for w in work if w["status"] != "done"]
    stage = min((w["stage"] for w in open_), key=int, default="8")
    head = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    out = [f"# State", "", f"*Generated by `method/status.py` from `work.tsv` and `risks.tsv`, at commit `{head}`, "
           f"{datetime.datetime.now(datetime.timezone.utc):%d %B %Y, %H:%M} UTC. Don't edit by hand.*", "",
           f"**Stage {stage}: {STAGES.get(stage, '')}** (`PLAN.md`, section 2.2).", ""]
    mine = [w for w in work if w["stage"] == stage]
    done = sum(w["status"] == "done" for w in mine)
    out += [f"**Its items:** {done} of {len(mine)} done.", ""]
    for w in mine:
        out.append(f"- {w['id']} ({w['owner']}, {w['status']}): {w['item']}")
    asks = [w for w in open_ if w["owner"] == "founder"]
    out += ["", "**What needs the founder:**"]
    out += [f"- {w['id']}, stage {w['stage']} ({w['status']}): {w['item']}" for w in asks] or ["- Nothing now."]
    nxt = str(int(stage) + 1)
    later = [w for w in work if w["stage"] == nxt]
    if later:
        out += ["", f"**Next, stage {nxt}: {STAGES.get(nxt, '')}** (in outline):"]
        out += [f"- {w['id']}: {w['item']}" for w in later]
    top = sorted((r for r in risks if r["status"] == "open"), key=lambda r: -int(r["likelihood"]) * int(r["impact"]))[:5]
    out += ["", "**Top risks** (`risks.tsv`):"]
    out += [f"- {r['id']} ({int(r['likelihood']) * int(r['impact'])}): {r['risk']}. {r['response']}" for r in top]
    open(os.path.join(ROOT, "STATE.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"STATE.md: stage {stage}, {done} of {len(mine)} items done, {len(asks)} for the founder, {len(top)} risks shown")


if __name__ == "__main__":
    main()
